                                'album', 'reconciliation'
                            )
                        ),
    state               text NOT NULL
                        CHECK (state IN (
                            'ready', 'delayed', 'leased', 'done',
                            'cancelled', 'dead'
                        )),
    priority            smallint NOT NULL DEFAULT 0
                        CHECK (priority BETWEEN -1000 AND 1000),
    priority_class      text NOT NULL DEFAULT 'historical'
                        CHECK (priority_class IN (
                            'critical', 'interactive', 'realtime',
                            'hot', 'historical', 'maintenance'
                        )),
    fairness_key        text NOT NULL DEFAULT 'global'
                        CHECK (btrim(fairness_key) <> ''),
    estimated_cost      numeric(18, 6) NOT NULL DEFAULT 1
                        CHECK (estimated_cost > 0),
    virtual_start       numeric(24, 6) NOT NULL DEFAULT 0
                        CHECK (virtual_start >= 0),
    virtual_finish      numeric(24, 6) NOT NULL DEFAULT 0
                        CHECK (virtual_finish >= virtual_start),
    queue_order         bigint NOT NULL DEFAULT nextval('job_queue_order_seq'),
    available_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
    lease_owner_worker_id text REFERENCES worker_instances(worker_id)
                        ON DELETE RESTRICT,
    lease_token         text,
    lease_expires_at    timestamptz,
    lease_heartbeat_at  timestamptz,
    lease_failures      integer NOT NULL DEFAULT 0 CHECK (lease_failures >= 0),
    attempt_count       integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    last_error          text NOT NULL DEFAULT '',
    enqueued_at         timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    completed_at        timestamptz,
    row_version         bigint NOT NULL DEFAULT 1 CHECK (row_version > 0),
    metadata            jsonb NOT NULL DEFAULT '{}'::jsonb
                        CHECK (jsonb_typeof(metadata) = 'object'),
    UNIQUE (queue_order),
    CHECK (
        (
            state = 'leased'
            AND lease_owner_worker_id IS NOT NULL
            AND lease_token IS NOT NULL
            AND btrim(lease_token) <> ''
            AND lease_expires_at IS NOT NULL
        )
        OR
        (
            state <> 'leased'
            AND lease_owner_worker_id IS NULL
            AND lease_token IS NULL
            AND lease_expires_at IS NULL
        )
    ),
    CHECK (
        (state IN ('done', 'cancelled', 'dead') AND completed_at IS NOT NULL)
        OR
        (state NOT IN ('done', 'cancelled', 'dead') AND completed_at IS NULL)
    ),
    CHECK (
        (priority_class = 'critical' AND priority BETWEEN 900 AND 1000)
        OR
        (priority_class = 'interactive' AND priority BETWEEN 600 AND 899)
        OR
        (priority_class = 'realtime' AND priority BETWEEN 300 AND 599)
        OR
        (priority_class = 'hot' AND priority BETWEEN 100 AND 299)
        OR
        (priority_class = 'historical' AND priority BETWEEN 0 AND 99)
        OR
        (priority_class = 'maintenance' AND priority BETWEEN -1000 AND -1)
    )
);

