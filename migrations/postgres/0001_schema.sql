                        REFERENCES media_jobs(job_id)
                        ON DELETE CASCADE,
    item_no             smallint,
    file_role           text NOT NULL
                        CHECK (file_role IN (
                            'download', 'partial', 'prepared', 'thumbnail',
                            'temporary'
                        )),
