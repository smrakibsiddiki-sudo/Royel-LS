BEGIN;

CREATE SCHEMA IF NOT EXISTS royells;
SET LOCAL search_path = royells, public;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '0';

CREATE TABLE IF NOT EXISTS schema_migrations (
    version             bigint PRIMARY KEY,
    description         text NOT NULL CHECK (btrim(description) <> ''),
    checksum_sha256     char(64) NOT NULL
                        CHECK (checksum_sha256 ~ '^[0-9a-f]{64}$'),
    applied_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    applied_by          text NOT NULL DEFAULT current_user
                        CHECK (btrim(applied_by) <> '')
);

CREATE TABLE IF NOT EXISTS migration_runs (
    migration_run_id    text PRIMARY KEY CHECK (btrim(migration_run_id) <> ''),
    source_version      text NOT NULL CHECK (btrim(source_version) <> ''),
    target_version      bigint NOT NULL,
    status              text NOT NULL
                        CHECK (status IN (
                            'planned', 'running', 'validating', 'succeeded',
                            'failed', 'rolled_back'
                        )),
    snapshot_started_at timestamptz,
    snapshot_finished_at timestamptz,
    started_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    finished_at         timestamptz,
    source_manifest     jsonb NOT NULL DEFAULT '{}'::jsonb
                        CHECK (jsonb_typeof(source_manifest) = 'object'),
    imported_counts     jsonb NOT NULL DEFAULT '{}'::jsonb
                        CHECK (jsonb_typeof(imported_counts) = 'object'),
    reconciliation      jsonb NOT NULL DEFAULT '{}'::jsonb
                        CHECK (jsonb_typeof(reconciliation) = 'object'),
    last_error          text NOT NULL DEFAULT '',
    CHECK (
        (status IN ('succeeded', 'failed', 'rolled_back') AND finished_at IS NOT NULL)
        OR
        (status NOT IN ('succeeded', 'failed', 'rolled_back'))
    )
);

CREATE TABLE IF NOT EXISTS bot_instances (
    instance_id         text PRIMARY KEY CHECK (btrim(instance_id) <> ''),
    boot_id             text NOT NULL UNIQUE CHECK (btrim(boot_id) <> ''),
    app_version         text NOT NULL CHECK (btrim(app_version) <> ''),
    deployment_id       text NOT NULL DEFAULT '',
    host_name           text NOT NULL DEFAULT '',
    process_id          integer CHECK (process_id IS NULL OR process_id > 0),
    status              text NOT NULL
                        CHECK (status IN (
                            'starting', 'recovering', 'running', 'draining',
                            'stopped', 'crashed', 'superseded'
                        )),
    started_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    ready_at            timestamptz,
    heartbeat_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
    shutdown_requested_at timestamptz,
    stopped_at          timestamptz,
    shutdown_reason     text NOT NULL DEFAULT '',
    metadata            jsonb NOT NULL DEFAULT '{}'::jsonb
                        CHECK (jsonb_typeof(metadata) = 'object'),
    CHECK (ready_at IS NULL OR ready_at >= started_at),
    CHECK (stopped_at IS NULL OR stopped_at >= started_at)
);

CREATE TABLE IF NOT EXISTS runtime_config (
    config_key          text PRIMARY KEY CHECK (btrim(config_key) <> ''),
    config_value        jsonb NOT NULL,
    value_type          text NOT NULL DEFAULT 'json'
                        CHECK (value_type IN (
                            'json', 'integer', 'number', 'boolean',
                            'string', 'duration'
                        )),
    config_version      bigint NOT NULL DEFAULT 1 CHECK (config_version > 0),
    is_secret           boolean NOT NULL DEFAULT false,
    updated_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_by          text NOT NULL DEFAULT 'migration'
                        CHECK (btrim(updated_by) <> ''),
    CHECK (is_secret = false)
);

CREATE TABLE IF NOT EXISTS redis_outbox (
    outbox_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type          text NOT NULL CHECK (btrim(event_type) <> ''),
    aggregate_type      text NOT NULL CHECK (btrim(aggregate_type) <> ''),
    aggregate_id        text NOT NULL CHECK (btrim(aggregate_id) <> ''),
    aggregate_version   bigint NOT NULL CHECK (aggregate_version >= 0),
    destination         text NOT NULL
                        CHECK (destination IN (
                            'download_queue', 'upload_queue', 'link_queue',
                            'reconciliation_queue', 'retry_queue',
                            'album_queue', 'runtime', 'config'
                        )),
    outbox_status       text NOT NULL DEFAULT 'pending'
                        CHECK (outbox_status IN (
                            'pending', 'publishing', 'published', 'dead'
                        )),
    payload             jsonb NOT NULL DEFAULT '{}'::jsonb
                        CHECK (jsonb_typeof(payload) = 'object'),
    available_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
    attempt_count       integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    lease_owner_instance_id text REFERENCES bot_instances(instance_id)
                        ON DELETE RESTRICT,
    lease_token         text,
    lease_expires_at    timestamptz,
    published_at        timestamptz,
    created_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    last_error          text NOT NULL DEFAULT '',
    UNIQUE (
        event_type,
        aggregate_type,
        aggregate_id,
        aggregate_version,
        destination
    ),
    CHECK (
        (
            outbox_status = 'publishing'
            AND lease_owner_instance_id IS NOT NULL
            AND lease_token IS NOT NULL
            AND btrim(lease_token) <> ''
            AND lease_expires_at IS NOT NULL
        )
        OR
        (
            outbox_status <> 'publishing'
            AND lease_owner_instance_id IS NULL
            AND lease_token IS NULL
            AND lease_expires_at IS NULL
        )
    ),
    CHECK (
        (outbox_status = 'published' AND published_at IS NOT NULL)
        OR
        (outbox_status <> 'published' AND published_at IS NULL)
    )
);

