CREATE OR REPLACE FUNCTION ensure_event_partitions(
    p_start_month date,
    p_month_count integer
) RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    parent_name text;
    month_start date;
    month_end date;
    partition_name text;
    offset_no integer;
BEGIN
    IF p_start_month IS NULL THEN
        RAISE EXCEPTION 'p_start_month is required';
    END IF;
    IF p_month_count < 1 OR p_month_count > 36 THEN
        RAISE EXCEPTION 'p_month_count must be between 1 and 36';
    END IF;

    FOREACH parent_name IN ARRAY ARRAY[
        'job_events',
        'delivery_history',
        'source_scan_events',
        'audit_events'
    ]
    LOOP
        FOR offset_no IN 0..(p_month_count - 1)
        LOOP
            month_start := (
                date_trunc('month', p_start_month::timestamp)
                + make_interval(months => offset_no)
            )::date;
            month_end := (month_start + interval '1 month')::date;
            partition_name := format(
                '%s_%s',
                parent_name,
                to_char(month_start, 'YYYYMM')
            );
            EXECUTE format(
                'CREATE TABLE IF NOT EXISTS royells.%I PARTITION OF royells.%I '
                'FOR VALUES FROM (%L) TO (%L)',
                partition_name,
                parent_name,
                month_start,
                month_end
            );
        END LOOP;
    END LOOP;
END;
$$;

SELECT ensure_event_partitions(
    (date_trunc('month', current_date) - interval '1 month')::date,
    5
);

